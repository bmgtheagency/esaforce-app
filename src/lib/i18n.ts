export function catalogText(value: string, language: Language) {
  if (language === "fr") return fr[value] ?? value
  if (language === "ar") return ar[value] ?? value
  return value
}

export const statusKeys = {
  received: "statusReceived",
  preparing: "statusPreparing",
  ready: "statusReady",
  collected: "statusCollected",
  cancelled: "statusCancelled",
} as const

export function statusText(status: string, language: Language) {
  const key = statusKeys[status as keyof typeof statusKeys]
  return key ? ui[language][key] : status
}

export function fulfillmentText(value: string, language: Language) {
  if (value === "pickup") return ui[language].takeaway
  if (value === "eat-in") return ui[language].eatIn
  return value
}

export const pickupTimes = [
  { value: "As soon as possible", key: "asap" },
  { value: "In 30 minutes", key: "thirtyMinutes" },
  { value: "In 1 hour", key: "oneHour" },
  { value: "Schedule at counter", key: "scheduleCounter" },
] as const

export function pickupTimeText(value: string, language: Language) {
  const option = pickupTimes.find((item) => item.value === value)
  return option ? ui[language][option.key] : value
}
